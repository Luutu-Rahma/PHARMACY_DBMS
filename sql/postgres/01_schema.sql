-- Supabase/PostgreSQL schema corresponding to sql/01_schema.sql.
-- Additive/explicit initializer: does not drop tables, data, or the database.
CREATE TABLE IF NOT EXISTS users (
    userid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname varchar(150) NOT NULL,
    username varchar(50) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(50) NOT NULL CHECK (role IN ('Admin', 'InventoryManager', 'Pharmacist', 'Cashier'))
);

CREATE TABLE IF NOT EXISTS categories (
    categoryid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoryname varchar(100) NOT NULL UNIQUE,
    description text
);

CREATE TABLE IF NOT EXISTS suppliers (
    supplierid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suppliername varchar(150) NOT NULL,
    contactperson varchar(100),
    phonenumber varchar(20),
    email varchar(100),
    address text
);

CREATE TABLE IF NOT EXISTS drugs (
    drugid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoryid integer NOT NULL REFERENCES categories(categoryid),
    genericname varchar(150) NOT NULL,
    brandname varchar(150),
    unitmeasure varchar(50) NOT NULL,
    unitprice numeric(12,2) NOT NULL CHECK (unitprice >= 0)
);

CREATE TABLE IF NOT EXISTS inventory_batches (
    batchid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drugid integer NOT NULL REFERENCES drugs(drugid),
    supplierid integer NOT NULL REFERENCES suppliers(supplierid),
    batchnumber varchar(50) NOT NULL,
    quantityreceived integer NOT NULL CHECK (quantityreceived > 0),
    quantityleft integer NOT NULL CHECK (quantityleft >= 0 AND quantityleft <= quantityreceived),
    mfd date NOT NULL,
    expirydate date NOT NULL CHECK (expirydate > mfd),
    unitprice numeric(12,2) NOT NULL CHECK (unitprice >= 0),
    CONSTRAINT uq_drug_batch UNIQUE (drugid, batchnumber)
);
CREATE INDEX IF NOT EXISTS idx_batches_fifo ON inventory_batches (drugid, expirydate, batchid);
CREATE INDEX IF NOT EXISTS idx_batches_available ON inventory_batches (expirydate, quantityleft);

CREATE TABLE IF NOT EXISTS transactions (
    transactionid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid integer NOT NULL REFERENCES users(userid),
    timestamp timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    totalamount numeric(12,2) NOT NULL DEFAULT 0,
    paymentmethod varchar(50) NOT NULL CHECK (paymentmethod IN ('Cash', 'Mobile Money'))
);
CREATE INDEX IF NOT EXISTS idx_transactions_timestamp ON transactions (timestamp);

CREATE TABLE IF NOT EXISTS sales_items (
    salesitemid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transactionid integer NOT NULL REFERENCES transactions(transactionid) ON DELETE CASCADE,
    batchid integer NOT NULL REFERENCES inventory_batches(batchid),
    quantitysold integer NOT NULL CHECK (quantitysold > 0),
    subtotal numeric(12,2) NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_sales_items_transaction ON sales_items (transactionid);
CREATE INDEX IF NOT EXISTS idx_sales_items_batch ON sales_items (batchid);
